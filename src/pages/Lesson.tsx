import { useEffect, useState } from "react"
import { useNavigate, useParams } from "react-router"

import Sidebar from "../components/Sidebar"
import {
  getTopicById,
  getLessonsForCurrentLevel,
} from "../data/learningData"
import {
  getCurrentLevel,
  getCompletedLessons,
  getLessonProgress,
  completeLesson,
  saveLessonQuizScore,
} from "../utils/progress"

type QuizQuestion = {
  question: string
  options: string[]
  correctAnswer: string
}

type QuizResponse = {
  questions: QuizQuestion[]
}

function Lesson() {
  const { id } = useParams()
  const navigate = useNavigate()

  const topicId = Number(id)

  const topic = getTopicById(topicId)

  const learningLevel = getCurrentLevel()

  const lessons = getLessonsForCurrentLevel(topicId)

  const [currentLessonIndex, setCurrentLessonIndex] =
    useState(0)

  const [quiz, setQuiz] =
    useState<QuizResponse | null>(null)

  const [selectedAnswers, setSelectedAnswers] =
    useState<Record<number, string>>({})

  const [quizSubmitted, setQuizSubmitted] =
    useState(false)

  const [quizScore, setQuizScore] =
    useState<number | null>(null)

  const [loadingQuiz, setLoadingQuiz] =
    useState(false)

  const [quizError, setQuizError] =
    useState("")

  const [completedLessons, setCompletedLessons] =
    useState<number[]>([])

  useEffect(() => {
    if (!topic || lessons.length === 0) {
      return
    }

    const savedLesson =
      localStorage.getItem(
        `ai-mentor-current-lesson-${topicId}-${learningLevel}`
      )

    if (savedLesson) {
      const savedIndex = Number(savedLesson)

      if (
        savedIndex >= 0 &&
        savedIndex < lessons.length
      ) {
        setCurrentLessonIndex(savedIndex)
      }
    }

    setCompletedLessons(
      getCompletedLessons(topicId)
    )
  }, [
    topic,
    topicId,
    learningLevel,
    lessons.length,
  ])

  if (!topic || lessons.length === 0) {
    return (
      <div className="flex min-h-screen bg-gray-50">
        <Sidebar />

        <main className="flex-1 p-8">
          <div className="mx-auto max-w-3xl rounded-2xl bg-white p-8 shadow-sm">
            <h1 className="text-2xl font-bold text-gray-900">
              Lesson not found
            </h1>

            <button
              onClick={() =>
                navigate("/learning-path")
              }
              className="mt-6 rounded-lg bg-blue-600 px-5 py-3 font-semibold text-white"
            >
              Back to Learning Path
            </button>
          </div>
        </main>
      </div>
    )
  }

  const lesson =
    lessons[currentLessonIndex]

  const lessonProgress =
    getLessonProgress(
      topicId,
      lessons.length
    )

  const openQuickCheck = async () => {
    setLoadingQuiz(true)
    setQuizError("")
    setQuiz(null)
    setSelectedAnswers({})
    setQuizSubmitted(false)
    setQuizScore(null)

    try {
      const response = await fetch(
        "https://ai-mentor-backend-zhfh.onrender.com/api/generate-lesson-quiz",
        {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
          },
          body: JSON.stringify({
            topic: topic.title,
            lessonTitle: lesson.title,
            lessonContent: `
${lesson.content}

Key Points:
${lesson.keyPoints.join("\n")}

Example:
${lesson.example}

Takeaway:
${lesson.takeaway}
`,
            learningLevel,
          }),
        }
      )

      const data =
        (await response.json()) as QuizResponse & {
          error?: string
        }

      if (!response.ok) {
        throw new Error(
          data.error ||
            "Failed to generate Quick Check"
        )
      }

      if (
        !data.questions ||
        !Array.isArray(data.questions)
      ) {
        throw new Error(
          "Invalid Quick Check generated by AI"
        )
      }

      setQuiz(data)
    } catch (error) {
      console.error(error)

      setQuizError(
        "Could not generate the Quick Check. Please try again."
      )
    } finally {
      setLoadingQuiz(false)
    }
  }

  const selectAnswer = (
    questionIndex: number,
    answer: string
  ) => {
    if (quizSubmitted) {
      return
    }

    setSelectedAnswers((previous) => ({
      ...previous,
      [questionIndex]: answer,
    }))
  }

  const submitQuickCheck = () => {
    if (!quiz) {
      return
    }

    const allAnswered =
      quiz.questions.every(
        (_, index) =>
          selectedAnswers[index]
      )

    if (!allAnswered) {
      return
    }

    let correct = 0

    quiz.questions.forEach(
      (question, index) => {
        if (
          selectedAnswers[index] ===
          question.correctAnswer
        ) {
          correct += 1
        }
      }
    )

    const percentage = Math.round(
      (correct / quiz.questions.length) *
        100
    )

    setQuizScore(percentage)
    setQuizSubmitted(true)

    saveLessonQuizScore(
      topicId,
      lesson.id,
      percentage
    )

    completeLesson(
      topicId,
      lesson.id
    )

    setCompletedLessons(
      getCompletedLessons(topicId)
    )
  }

  const continueToNextLesson = () => {
    if (!quizSubmitted) {
      return
    }

    if (
      currentLessonIndex <
      lessons.length - 1
    ) {
      const nextIndex =
        currentLessonIndex + 1

      localStorage.setItem(
        `ai-mentor-current-lesson-${topicId}-${learningLevel}`,
        nextIndex.toString()
      )

      setCurrentLessonIndex(nextIndex)

      setQuiz(null)
      setSelectedAnswers({})
      setQuizSubmitted(false)
      setQuizScore(null)
      setQuizError("")

      window.scrollTo({
        top: 0,
        behavior: "smooth",
      })

      return
    }

    navigate(
      `/topic-challenge/${topicId}`
    )
  }

  const askAIAboutQuestion = (
    question: QuizQuestion,
    questionNumber: number
  ) => {
    navigate("/ai-tutor", {
      state: {
        questionHelp: {
          question: question.question,
          options: question.options,
          topic: topic.title,
          lesson: lesson.title,
          learningLevel,
          questionNumber,
        },
      },
    })
  }

  const completedCurrentLesson =
    completedLessons.includes(lesson.id)

  return (
    <div className="flex min-h-screen bg-gray-50">
      <Sidebar />

      <main className="flex-1 p-8">
        <div className="mx-auto max-w-5xl">

          <div className="rounded-2xl bg-white p-8 shadow-sm">

            <div className="flex items-center justify-between">

              <span className="rounded-full bg-blue-50 px-4 py-2 text-sm font-semibold text-blue-600">
                {learningLevel}
              </span>

              <span className="text-sm font-medium text-gray-500">
                Lesson {currentLessonIndex + 1} of{" "}
                {lessons.length}
              </span>

            </div>

            <h1 className="mt-6 text-3xl font-bold text-gray-900">
              {lesson.title}
            </h1>

            <p className="mt-3 text-lg text-gray-600">
              {topic.title}
            </p>

            <div className="mt-6">

              <div className="flex items-center justify-between text-sm">
                <span className="font-semibold text-gray-700">
                  Lesson Progress
                </span>

                <span className="font-semibold text-blue-600">
                  {Math.round(
                    ((currentLessonIndex + 1) /
                      lessons.length) *
                      100
                  )}
                  %
                </span>
              </div>

              <div className="mt-2 h-2 rounded-full bg-gray-100">
                <div
                  className="h-2 rounded-full bg-blue-600 transition-all"
                  style={{
                    width: `${
                      ((currentLessonIndex + 1) /
                        lessons.length) *
                      100
                    }%`,
                  }}
                />
              </div>

            </div>

            <div className="mt-10 rounded-2xl bg-gray-50 p-7">

              <h2 className="text-2xl font-bold text-gray-900">
                Learn
              </h2>

              <p className="mt-5 text-lg leading-8 text-gray-700">
                {lesson.content}
              </p>

            </div>

            <div className="mt-8">

              <h2 className="text-2xl font-bold text-gray-900">
                Key Points
              </h2>

              <div className="mt-4 space-y-3">

                {lesson.keyPoints.map(
                  (point, index) => (
                    <div
                      key={index}
                      className="rounded-xl border border-gray-200 bg-white p-5"
                    >
                      <p className="text-gray-700">
                        • {point}
                      </p>
                    </div>
                  )
                )}

              </div>

            </div>

            <div className="mt-8 rounded-2xl border border-blue-100 bg-blue-50 p-6">

              <h2 className="text-xl font-bold text-gray-900">
                Real-World Example
              </h2>

              <p className="mt-3 leading-7 text-gray-700">
                {lesson.example}
              </p>

            </div>

            <div className="mt-6 rounded-2xl border border-green-100 bg-green-50 p-6">

              <h2 className="text-xl font-bold text-gray-900">
                Key Takeaway
              </h2>

              <p className="mt-3 leading-7 text-gray-700">
                {lesson.takeaway}
              </p>

            </div>

            <div className="mt-8 rounded-2xl border border-purple-100 bg-purple-50 p-6">

              <h2 className="text-xl font-bold text-gray-900">
                Quick Check
              </h2>

              <p className="mt-3 text-gray-600">
                Complete this lesson and take a short
                AI-generated Quick Check based specifically
                on what you just learned.
              </p>

              <div className="mt-4 flex flex-wrap gap-2">

                {lesson.questionTypes.map(
                  (type) => (
                    <span
                      key={type}
                      className="rounded-full bg-white px-3 py-1 text-sm font-medium text-purple-600"
                    >
                      {type === "mcq"
                        ? "MCQ"
                        : type === "conceptual"
                        ? "Conceptual"
                        : type === "scenario"
                        ? "Scenario"
                        : "Numerical"}
                    </span>
                  )
                )}

              </div>

            </div>

            <div className="mt-6 rounded-2xl border border-blue-100 bg-white p-6 shadow-sm">

              <div className="flex items-center gap-3">

                <div className="flex h-10 w-10 items-center justify-center rounded-full bg-blue-100">
                  🤖
                </div>

                <div>
                  <h2 className="font-bold text-gray-900">
                    AI Mentor
                  </h2>

                  <p className="text-sm text-gray-500">
                    Need help with this lesson?
                  </p>
                </div>

              </div>

              <p className="mt-4 leading-7 text-gray-600">
                Ask AI Mentor to explain this lesson
                in simpler words, give you another
                example, or help you understand a
                difficult concept.
              </p>

              <button
                onClick={() =>
                  navigate("/ai-tutor", {
                    state: {
                      lessonHelp: {
                        topic: topic.title,
                        lesson: lesson.title,
                        lessonContent:
                          lesson.content,
                        learningLevel,
                      },
                    },
                  })
                }
                className="mt-5 rounded-lg border border-blue-600 px-5 py-3 font-semibold text-blue-600 hover:bg-blue-50"
              >
                Ask AI Mentor
              </button>

            </div>

            <div className="mt-8 flex items-center justify-between border-t border-gray-200 pt-6">

              <button
                onClick={() =>
                  navigate("/learning-path")
                }
                className="rounded-lg border border-gray-300 px-5 py-3 font-semibold text-gray-700 hover:bg-gray-50"
              >
                Back to Learning Path
              </button>

              <button
                onClick={openQuickCheck}
                disabled={loadingQuiz}
                className="rounded-lg bg-blue-600 px-6 py-3 font-semibold text-white hover:bg-blue-700 disabled:cursor-not-allowed disabled:opacity-50"
              >
                {loadingQuiz
                  ? "Generating Quick Check..."
                  : completedCurrentLesson
                  ? "Retake Quick Check →"
                  : "Take Quick Check →"}
              </button>

            </div>

            {quizError && (
              <p className="mt-4 text-center text-sm text-red-600">
                {quizError}
              </p>
            )}

          </div>

          {quiz && (
            <div className="mt-8 rounded-2xl bg-white p-8 shadow-sm">

              <div className="flex items-center justify-between">

                <div>
                  <p className="text-sm font-semibold text-purple-600">
                    Quick Check
                  </p>

                  <h2 className="mt-1 text-2xl font-bold text-gray-900">
                    {lesson.title}
                  </h2>
                </div>

                <span className="rounded-full bg-blue-50 px-4 py-2 text-sm font-semibold text-blue-600">
                  {learningLevel}
                </span>

              </div>

              <p className="mt-3 text-gray-600">
                Answer the questions based on the
                lesson you just completed.
              </p>

              <div className="mt-8 space-y-8">

                {quiz.questions.map(
                  (question, questionIndex) => {

                    const selected =
                      selectedAnswers[
                        questionIndex
                      ]

                    const isCorrect =
                      selected ===
                      question.correctAnswer

                    return (
                      <div
                        key={questionIndex}
                        className="rounded-2xl border border-gray-200 p-6"
                      >

                        <div className="flex items-start gap-3">

                          <span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-full bg-purple-100 font-semibold text-purple-600">
                            {questionIndex + 1}
                          </span>

                          <h3 className="text-lg font-semibold leading-7 text-gray-900">
                            {question.question}
                          </h3>

                        </div>

                        <div className="mt-5 space-y-3">

                          {question.options.map(
                            (option) => {

                              const selectedOption =
                                selected ===
                                option

                              const correctOption =
                                quizSubmitted &&
                                option ===
                                  question.correctAnswer

                              const wrongSelected =
                                quizSubmitted &&
                                selectedOption &&
                                !isCorrect

                              return (
                                <button
                                  key={option}
                                  onClick={() =>
                                    selectAnswer(
                                      questionIndex,
                                      option
                                    )
                                  }
                                  disabled={
                                    quizSubmitted
                                  }
                                  className={`w-full rounded-xl border p-4 text-left transition ${
                                    correctOption
                                      ? "border-green-500 bg-green-50"
                                      : wrongSelected
                                      ? "border-red-500 bg-red-50"
                                      : selectedOption
                                      ? "border-blue-600 bg-blue-50"
                                      : "border-gray-200 hover:bg-gray-50"
                                  }`}
                                >
                                  {option}
                                </button>
                              )
                            }
                          )}

                        </div>

                        <button
                          onClick={() =>
                            askAIAboutQuestion(
                              question,
                              questionIndex + 1
                            )
                          }
                          className="mt-4 rounded-lg border border-purple-500 px-4 py-2 text-sm font-semibold text-purple-600 hover:bg-purple-50"
                        >
                          🤖 Ask AI Mentor About This Question
                        </button>

                        {quizSubmitted && (
                          <div
                            className={`mt-4 rounded-xl p-4 ${
                              isCorrect
                                ? "bg-green-50"
                                : "bg-orange-50"
                            }`}
                          >
                            <p
                              className={`font-semibold ${
                                isCorrect
                                  ? "text-green-700"
                                  : "text-orange-700"
                              }`}
                            >
                              {isCorrect
                                ? "Correct!"
                                : "Review this question with AI Mentor if needed."}
                            </p>

                            {!isCorrect && (
                              <p className="mt-1 text-sm text-gray-700">
                                You can ask AI Mentor to
                                explain this question
                                step by step.
                              </p>
                            )}
                          </div>
                        )}

                      </div>
                    )
                  }
                )}

              </div>

              {!quizSubmitted ? (
                <button
                  onClick={submitQuickCheck}
                  disabled={
                    quiz.questions.some(
                      (_, index) =>
                        !selectedAnswers[index]
                    )
                  }
                  className="mt-8 rounded-lg bg-blue-600 px-6 py-3 font-semibold text-white hover:bg-blue-700 disabled:cursor-not-allowed disabled:opacity-50"
                >
                  Submit Quick Check
                </button>
              ) : (
                <div className="mt-8 rounded-2xl border border-blue-100 bg-blue-50 p-6">

                  <p className="text-sm font-semibold text-blue-600">
                    AI Quick Check Result
                  </p>

                  <p className="mt-2 text-4xl font-bold text-gray-900">
                    {quizScore}%
                  </p>

                  <p className="mt-2 text-gray-600">
                    Your answers have been recorded for
                    this lesson.
                  </p>

                  <button
                    onClick={
                      continueToNextLesson
                    }
                    className="mt-5 rounded-lg bg-blue-600 px-6 py-3 font-semibold text-white hover:bg-blue-700"
                  >
                    {currentLessonIndex <
                    lessons.length - 1
                      ? "Next Lesson →"
                      : "Take Topic Challenge →"}
                  </button>

                </div>
              )}

              <button
                onClick={() => {
                  setQuiz(null)
                  setSelectedAnswers({})
                  setQuizSubmitted(false)
                  setQuizScore(null)
                }}
                className="mt-4 rounded-lg border border-gray-300 px-5 py-3 font-semibold text-gray-700 hover:bg-gray-50"
              >
                Review Lesson
              </button>

            </div>
          )}

          <div className="mt-6 text-center text-sm text-gray-500">
            Overall topic progress: {lessonProgress}%
          </div>

        </div>
      </main>
    </div>
  )
}

export default Lesson
